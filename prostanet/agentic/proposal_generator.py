def skill_invoke_dry_run(draft: ProposalDraft) -> list[str]:
    """Returns lista de cambios que el skill chain HARÍA si fueran invoked.

    En LXXXVIII bootstrap esto es DRY-RUN — describe lo que ocurriría sin
    invocar las skills. Iteraciones LXXXIX+ conectan cada skill real.
    """
    actions = []
    actions.append(f"[1/3] Read gap context (pillar {draft.gap.pillar_id}, severity {draft.gap.severity})")
    if draft.skill_chain:
        actions.append(f"[2/3] Invoke skills: {' → '.join(draft.skill_chain)}")
        actions.append(f"[3/3] Write artifact: {draft.proposed_artifact}")
    else:
        actions.append("[2/3] No skill chain (manual review or out-of-loop)")
    if draft.blocked_human:
        actions.append("[!] BLOCKED: human signoff required")
    return actions
