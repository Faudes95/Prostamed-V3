"""Faubot Agentic Loop — Proposal Generator (LXXXVIII).

Routes a `Gap` to the appropriate skill client + builds a `Proposal`
with concrete `proposed_changes` (file paths, content seeds, validation
checks).

Bootstrap LXXXVIII: este módulo es un STUB en modo Shadow — describe la
estructura de cambios sin invocar realmente las skills. Iteraciones
posteriores conectarán cada client a la skill bundled correspondiente
(docx/xlsx/pubmed/code-review).

API:
    proposal = generate_proposal_for_gap(gap)  # ProposalDraft
    skill_invoke_dry_run(proposal)              # → list[str] of changes that WOULD be made
"""
from __future__ import annotations

from dataclasses import dataclass, field
from pathlib import Path
from typing import Any

from prostanet.agentic.compliance_scorer import Gap

PROJECT_ROOT = Path(__file__).parent.parent.parent


@dataclass
class ProposalDraft:
    """Draft de cambio generado por proposal_generator."""
    gap: Gap
    skill_chain: list[str]  # e.g., ["docx", "fda-medtech-compliance-auditor"]
    proposed_artifact: str  # e.g., "regulatory/sops/SOP-DCG-001.docx"
    proposed_content_seed: str = ""  # frontmatter / template seed
    validation_checks: list[str] = field(default_factory=list)
    estimated_iterations_to_close: int = 1
    blocked_human: bool = False  # True si requires human signoff (e.g., prospective protocol)

    def to_dict(self) -> dict[str, Any]:
        return {
            "gap_kind": self.gap.kind,
            "gap_pillar": self.gap.pillar_id,
            "gap_severity": self.gap.severity,
            "skill_chain": self.skill_chain,
            "proposed_artifact": self.proposed_artifact,
            "proposed_content_seed_len": len(self.proposed_content_seed),
            "validation_checks": self.validation_checks,
            "estimated_iterations_to_close": self.estimated_iterations_to_close,
            "blocked_human": self.blocked_human,
        }


def generate_proposal_for_gap(gap: Gap) -> ProposalDraft:
    """Router principal: dispatch a la sub-función según gap.kind."""
    kind = gap.kind.split(":")[0]

    routers = {
        "regulatory_doc_missing": _route_regulatory_doc,
        "cds_criteria_yaml_missing": _route_cds_criteria,
        "cds_criteria_incomplete": _route_cds_criteria,
        "iec62304_class_unassigned": _route_iec62304_class,
        "iec62304_class_undocumented": _route_iec62304_class,
        "sop_missing": _route_sop,
        "qms_roster_missing": _route_qms_roster,
        "qms_roles_unassigned": _route_qms_roster,
        "part11_checklist_missing": _route_part11,
        "part11_control_missing": _route_part11,
        "iec62304_test_mapping_incomplete": _route_iec62304_test_mapping,
        "sbom_unpinned_dependencies": _route_sbom,
        "sbom_missing": _route_sbom,
        "sbom_incomplete": _route_sbom,
        "cve_critical_open": _route_cve,
        "cve_scan_tool_missing": _route_cve_tool,
        "sdp_missing": _route_sdp,
        "fmea_file_missing": _route_fmea,
        "fmea_entry_missing": _route_fmea,
        "fmea_mitigations_incomplete": _route_fmea,
        "tir57_addendum_missing": _route_tir57,
        "trial_evidence_missing": _route_trial_evidence,
        "retro_validation_missing": _route_retro_validation,
        "prospective_protocol_missing": _route_prospective_protocol,
        "prospective_data_incomplete": _route_prospective_data,
        "stride_threat_model_missing": _route_stride,
        "stride_threat_categories_incomplete": _route_stride,
        "disclosure_policy_missing": _route_disclosure,
        "vex_addendum_missing": _route_vex,
        "traceability_matrix_missing": _route_traceability,
        "traceability_row_missing": _route_traceability,
        "cr_log_missing": _route_cr_log,
        "design_input_baseline_unlocked": _route_design_baseline,
    }
    handler = routers.get(kind, _route_default)
    return handler(gap)


