# -*- coding: utf-8 -*-
"""Auditoría #14 — Catálogo canónico de pacientes insignia por estudio pivotal.

Cada entrada describe el "paciente insignia" del trial: el perfil clínico
publicado en el ensayo pivotal (criterios de inclusión + características
medianas), las comorbilidades relevantes, los efectos adversos clave y las
contraindicaciones que ProstaNet debe poder reconocer y procesar.

Este registro sirve como espejo de auditoría para `trial_matching_engine.py`
y como input estable para los tests de cobertura clínica
(`tests/test_pivotal_trials_audit.py`).

Cada `PivotalPatientProfile` cumple cuatro propósitos:

1. **Diagnóstico**: el campo ``payload`` es directamente alimentable a
   ``StateClassifierService`` y produce el ``expected_state`` declarado.
2. **Elegibilidad**: el ``trial_code`` debe matchear positivamente vía
   ``match_patient_to_trials(payload)``.
3. **Comorbilidades / AEs**: el campo ``comorbidity_signals`` lista las
   señales que el motor de selección ARPI / DDI debe ver y reaccionar.
4. **Contraindicaciones**: ``contraindication_signals`` lista los hard-blocks
   o cautions que deben evitar prescribir el régimen del trial al paciente
   insignia cuando aplica (p. ej. seizure history para AFFIRM/PREVAIL).

Las referencias bibliográficas se conservan en `evidence_registry/data.py` y
en los `evidence_tags` del catálogo del trial-matching engine.
"""
from __future__ import annotations

from dataclasses import dataclass, field
from typing import Any


@dataclass(frozen=True)
class PivotalPatientProfile:
    """Snapshot canónico del paciente insignia del trial."""

    trial_code: str
    nct_id: str
    expected_state: str
    expected_treatment_keywords: tuple[str, ...]
    payload: dict[str, Any]
    comorbidity_signals: tuple[str, ...] = field(default_factory=tuple)
    adverse_event_signals: tuple[str, ...] = field(default_factory=tuple)
    contraindication_signals: tuple[str, ...] = field(default_factory=tuple)
    notes: str = ""


