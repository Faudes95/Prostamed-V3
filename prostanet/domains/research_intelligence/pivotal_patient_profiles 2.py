def get_profile(trial_code: str) -> PivotalPatientProfile | None:
    """Devuelve el perfil insignia por código de trial."""
    for profile in PIVOTAL_PATIENT_PROFILES:
        if profile.trial_code == trial_code:
            return profile
    return None


